namespace Domain;

/// <summary>
/// Enumeration of doctor specializations
/// </summary>
public enum Specialization
{
    /// <summary>
    /// General practitioner providing primary care
    /// </summary>
    Therapist,

    /// <summary>
    /// Specialist performing surgical operations
    /// </summary>
    Surgeon,

    /// <summary>
    /// Heart and cardiovascular system specialist
    /// </summary>
    Cardiologist,

    /// <summary>
    /// Nervous system and brain specialist
    /// </summary>
    Neurologist,

    /// <summary>
    /// Children's health specialist
    /// </summary>
    Pediatrician,

    /// <summary>
    /// Oral health and teeth specialist
    /// </summary>
    Dentist,

    /// <summary>
    /// Eye and vision specialist
    /// </summary>
    Ophthalmologist,

    /// <summary>
    /// Skin, hair, and nails specialist
    /// </summary>
    Dermatologist,

    /// <summary>
    /// Bone and joint specialist
    /// </summary>
    Orthopedist,
}